import assert from 'node:assert/strict'
import {authorizeRun,admission,reserveRequest,settleRequest,scoreFunctional,FUNCTIONAL_RUBRIC,REVIEW_RUBRIC} from './production-frontend-eval-core.mjs'
const old={limitCny:20,spentCny:1.75972304,reservations:{legacy:2.162688},records:[{id:'historical'}],paused:true}
assert.throws(()=>authorizeRun(old,{runId:'fixture'}))
const {ledger,run}=authorizeRun(old,{runId:'fixture',at:'fixture',priorHostsEnded:true,transportPreflight:true,authorization:'Unit fixture only; not paid authorization'})
assert.equal(old.paused,true);assert.equal(old.limitCny,20)
assert.equal(ledger.limitCny,30);assert.deepEqual(ledger.reservations,old.reservations)
assert.deepEqual(ledger.records,old.records)
const check=reservation=>admission({ledger,run,reservation,now:0,expiresAt:'2099-01-01'})
assert.equal(check(2.162688).allowed,true)
assert.equal(check(10.001).reason,'run-budget')
assert.equal(admission({ledger,run,reservation:1,now:Date.now(),expiresAt:'2000-01-01'}).reason,'price-expired')
reserveRequest(ledger,run,{id:'call1',costCny:2.162688})
assert.equal(check(8).allowed,false)
assert.equal(settleRequest(ledger,run,{reservationId:'call1',costCny:0.25}),true)
assert.equal(settleRequest(ledger,run,{reservationId:'call1',costCny:0.25}),false)
assert.equal(run.spentCny,0.25);assert.equal(ledger.reservations.legacy,2.162688)
reserveRequest(ledger,run,{id:'unknown',costCny:2.162688})
settleRequest(ledger,run,{reservationId:'unknown',costCny:null})
assert.equal(run.paused,true);assert.equal(ledger.paused,true)
assert.equal(run.reservations.unknown,2.162688);assert.equal(check(0.001).reason,'paused')
assert.equal(scoreFunctional(Object.fromEntries(Object.keys(FUNCTIONAL_RUBRIC).map(key=>[key,true]))).earned,60)
assert.equal(scoreFunctional({}).earned,0)
assert.equal(Object.values(REVIEW_RUBRIC.visual).reduce((a,b)=>a+b),20)
assert.equal(Object.values(REVIEW_RUBRIC.accessibility).reduce((a,b)=>a+b),10)
assert.equal(Object.values(REVIEW_RUBRIC.maintainability).reduce((a,b)=>a+b),10)
console.log(JSON.stringify({status:'Pass',checks:20,paidCalls:0,productionLedgerChanged:false}))
